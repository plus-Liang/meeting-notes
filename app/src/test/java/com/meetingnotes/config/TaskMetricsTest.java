package com.meetingnotes.config;

import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.data.redis.core.ListOperations;
import org.springframework.data.redis.core.StringRedisTemplate;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.Mockito.when;

/**
 * T4.84/P-25：TaskMetrics 业务指标语义——真 H2 钉 SQL 与节流（mock JdbcTemplate 的 query(String,
 * ResultSetExtractor) stub 在本环境不生效，见回报自曝；真库是 LoginLockoutDbTest/StartupRecoveryDbTest
 * 的既有先例，且把「GROUP BY 一条 SQL」的真实行为一起钉住）：
 * ①首次抓取装载 DB 计数与 Redis 深度；②cacheSeconds 内重复读取不重查（改库后 gauge 值不变）；
 * ③cacheSeconds=0 每次重查（改库后 gauge 值更新）；④表被删（SQL 异常）→ 保留旧值、assertDoesNotThrow。
 * SimpleMeterRegistry；Redis 用 mock（ListOperations 接口）；禁 Thread.sleep。
 */
@ExtendWith(MockitoExtension.class)
class TaskMetricsTest {

    private static final String URL = "jdbc:h2:mem:taskmetrics;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    private final SimpleMeterRegistry registry = new SimpleMeterRegistry();
    private JdbcTemplate jdbc;
    private TaskMetrics metrics;

    @Mock
    private StringRedisTemplate redis;
    @Mock
    private ListOperations<String, String> listOps;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status VARCHAR(16))");
    }

    private TaskMetrics newMetrics(long cacheSeconds) {
        return new TaskMetrics(jdbc, redis, registry, "meetingnotes:task-queue", cacheSeconds);
    }

    private void insert(String status, int n) {
        for (int i = 0; i < n; i++) {
            jdbc.update("INSERT INTO task (status) VALUES (?)", status);
        }
    }

    private void stubRedis(Long depth) {
        when(redis.opsForList()).thenReturn(listOps);
        when(listOps.size("meetingnotes:task-queue")).thenReturn(depth);
    }

    private double taskCountGauge(String status) {
        return registry.get("meetingnotes.task.count").tag("status", status).gauge().value();
    }

    private double queueDepthGauge() {
        return registry.get("meetingnotes.queue.depth").gauge().value();
    }

    /** ① 首次抓取：gauge 值 = DB 真实计数（真 SQL 语义钉住）。 */
    @Test
    void firstScrapeLoadsCountsFromDatabase() {
        insert("DONE", 3);
        insert("PENDING", 1);
        stubRedis(7L);
        metrics = newMetrics(60);

        assertEquals(3.0, taskCountGauge("DONE"));
        assertEquals(1.0, taskCountGauge("PENDING"));
        assertEquals(0.0, taskCountGauge("RETRYING"), "未出现的状态档 = 0");
        assertEquals(7.0, queueDepthGauge());
    }

    /** ② 同一缓存窗口内再次读取不重查：改库后 gauge 仍是旧值（节流生效）。 */
    @Test
    void secondReadWithinCacheWindowDoesNotQueryAgain() {
        insert("DONE", 3);
        stubRedis(7L);
        metrics = newMetrics(60);
        assertEquals(3.0, taskCountGauge("DONE"));

        insert("DONE", 6); // DB 变为 9 行 DONE
        assertEquals(3.0, taskCountGauge("DONE"), "cacheSeconds 窗口内必须返回缓存（不重查）");
        assertEquals(7.0, queueDepthGauge());
    }

    /** ③ cacheSeconds=0（每次都过期）→ 改库后再次读取立即反映新值（触发第二次查询）。 */
    @Test
    void expiredCacheTriggersSecondQueryAndUpdatesValue() {
        insert("DONE", 3);
        stubRedis(7L);
        metrics = newMetrics(0);
        assertEquals(3.0, taskCountGauge("DONE"));

        insert("DONE", 6); // DB 变为 9 行 DONE
        assertEquals(9.0, taskCountGauge("DONE"), "cacheSeconds=0 时第二次读取必须重查并更新");
    }

    /** ④ 表被删（SQL 异常）→ gauge 保留上一次值、assertDoesNotThrow（/actuator/prometheus 不 500）。 */
    @Test
    void queryFailureKeepsLastValueAndNeverThrows() {
        insert("DONE", 3);
        stubRedis(7L);
        metrics = newMetrics(0);
        assertEquals(3.0, taskCountGauge("DONE"));

        jdbc.execute("DROP TABLE task"); // 下次刷新 SQL 异常

        assertDoesNotThrow(() -> taskCountGauge("DONE"));
        assertDoesNotThrow(this::queueDepthGauge);
        assertEquals(3.0, taskCountGauge("DONE"), "异常时必须保留上一次的值");
        assertEquals(7.0, queueDepthGauge(), "Redis 深度同样保留旧值");
    }

}
