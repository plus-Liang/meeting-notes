package com.meetingnotes.worker;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * T4.62 S2：陈旧 PENDING 判据（findStalePending 的方向）与 touch 的真实执行——
 * 真实 H2（MODE=PostgreSQL）钉住 SQL 方向：< cutoff 选中陈旧行、排除新鲜行（A2 负向对照的落点：
 * 把 StalePendingQueries 里的 < 翻成 >，本测试立即变红——mock jdbc 层面翻转会假绿）。
 */
class StalePendingQueriesTest {

    private static final String URL = "jdbc:h2:mem:sweepqueries;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    private JdbcTemplate jdbc;
    private StalePendingQueries queries;
    private Timestamp runStart;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), updated_at TIMESTAMP)");
        queries = new StalePendingQueries(jdbc);
        runStart = new Timestamp(System.currentTimeMillis() - 1000L);
    }

    private long insert(String status, Timestamp updatedAt) {
        jdbc.update("INSERT INTO task (status, updated_at) VALUES (?, ?)", status, updatedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    /** 方向语义：早于 cutoff 的陈旧行被选中、新鲜行被排除（真 SQL 执行）。 */
    @Test
    void findStalePendingSelectsOnlyStaleRows() {
        long staleId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));
        long freshId = insert("PENDING", runStart);

        java.util.List<Long> ids = queries.findStalePending(StalePendingQueries.cutoff(2));

        assertEquals(1, ids.size(), "只选中陈旧行");
        assertEquals(staleId, ids.get(0), "选中且仅选中早于阈值的行");
        assertTrue(!ids.contains(freshId), "新鲜行不得入选");
    }

    /** touch：updated_at 真被刷新到当前时刻之后。 */
    @Test
    void touchReallyRefreshesUpdatedAt() {
        long id = insert("PENDING", runStart);

        queries.touch(id);

        Integer refreshed = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at > ?", Integer.class, id, runStart);
        assertEquals(1, refreshed, "touch 应把 updated_at 刷新到运行时刻之后");
    }

    /** cutoff(2)：正好 2 分钟前的行入选、1.5 分钟前的不入选（边界方向）。 */
    @Test
    void cutoffBoundaryIsExclusiveTowardsFresh() {
        long exactlyStale = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(125)));
        long stillFresh = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(90)));

        java.util.List<Long> ids = queries.findStalePending(StalePendingQueries.cutoff(2));

        assertTrue(ids.contains(exactlyStale), "125s 前（>2min）的行应入选");
        assertTrue(!ids.contains(stillFresh), "90s 前（<2min）的行不得入选");
    }
}
