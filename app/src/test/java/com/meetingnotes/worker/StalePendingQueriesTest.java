package com.meetingnotes.worker;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;
import java.time.temporal.ChronoUnit;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * T4.62 S2：陈旧 PENDING 判据（findStalePending 的方向）与 touch 的真实执行——
 * 真实 H2（MODE=PostgreSQL）钉住 SQL 方向：< cutoff 选中陈旧行、排除新鲜行（A2 负向对照的落点：
 * 把 StalePendingQueries 里的 < 翻成 >，本测试立即变红——mock jdbc 层面翻转会假绿）。
 * T4.79/P-02：findTaskStatus（真 SQL，参数必须真绑定——T4.79 真栈曾因漏传 id 参数出现
 * "syntax error at end of input" 假绿，mock 层测不出）在此钉住。
 * T4.94：reclaimZombieRunning 已删（僵尸 RUNNING 回收收敛到 TaskCrashRecovery，SQL 由 TaskCrashRecoveryTest 真库覆盖）。
 */
class StalePendingQueriesTest {

    private static final String URL = "jdbc:h2:mem:sweepqueries;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    private JdbcTemplate jdbc;
    private StalePendingQueries queries;
    private Timestamp runStart;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), updated_at TIMESTAMP)");
        queries = new StalePendingQueries(jdbc);
        runStart = new Timestamp(System.currentTimeMillis() - 1000L);
    }

    private long insert(String status, Timestamp updatedAt) {
        jdbc.update("INSERT INTO task (status, updated_at) VALUES (?, ?)", status, updatedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    /** 方向语义：早于 cutoff 的陈旧行被选中、新鲜行被排除（真 SQL 执行）。 */
    @Test
    void findStalePendingSelectsOnlyStaleRows() {
        long staleId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));
        long freshId = insert("PENDING", runStart);

        java.util.List<Long> ids = queries.findStalePending(StalePendingQueries.cutoff(2));

        assertEquals(1, ids.size(), "只选中陈旧行");
        assertEquals(staleId, ids.get(0), "选中且仅选中早于阈值的行");
        assertTrue(!ids.contains(freshId), "新鲜行不得入选");
    }

    /** touch：updated_at 真被刷新到当前时刻之后。 */
    @Test
    void touchReallyRefreshesUpdatedAt() {
        long id = insert("PENDING", runStart);

        queries.touch(id);

        Integer refreshed = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at > ?", Integer.class, id, runStart);
        assertEquals(1, refreshed, "touch 应把 updated_at 刷新到运行时刻之后");
    }

    /** cutoff(2)：正好 2 分钟前的行入选、1.5 分钟前的不入选（边界方向）。 */
    @Test
    void cutoffBoundaryIsExclusiveTowardsFresh() {
        long exactlyStale = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(125)));
        long stillFresh = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(90)));

        java.util.List<Long> ids = queries.findStalePending(StalePendingQueries.cutoff(2));

        assertTrue(ids.contains(exactlyStale), "125s 前（>2min）的行应入选");
        assertTrue(!ids.contains(stillFresh), "90s 前（<2min）的行不得入选");
    }

    /** T4.67-fix F5（S8 改判）：返回顺序 = updated_at ASC（最旧在前）——真 H2 三行不同 updated_at 钉住方向。
     *  A2 变异①落点：把 SQL 改回 DESC 时本用例必红（DESC+头插曾被注释成「先来先服务」，真栈实测是新者先）。 */
    @Test
    void findStalePendingReturnsOldestFirst() {
        long newest = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(100)));
        long middle = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(200)));
        long oldest = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(300)));

        java.util.List<Long> ids = queries.findStalePending(StalePendingQueries.cutoff(1));

        assertEquals(3, ids.size(), "三行都早于 cutoff（1 分钟），应全部入选");
        assertEquals(java.util.List.of(oldest, middle, newest), ids, "必须按 updated_at ASC（最旧在前）返回");
    }

    /** T4.67-fix F6（S1 后半）：阈值 0 的边界反例——cutoff 是严格 <：updated_at 恰等于 cutoff（刚插入=now）
     *  的行不入选；比 cutoff 旧 1 分钟的行入选。同时证明 cutoff 随参数走（0 分钟也生效，不是恒用默认 2）。 */
    @Test
    void zeroMinuteCutoffIsStrictAndParametrized() {
        /* 阈值 0 分钟：cutoff = now。先截齐到毫秒再当 updated_at 用——H2 TIMESTAMP(6) 对列值截到微秒、
         * 查询参数保持全精度，不截齐的话「等于」会被存成「严格小于」，用例随机红。 */
        Timestamp cutoff = Timestamp.from(StalePendingQueries.cutoff(0).toInstant().truncatedTo(ChronoUnit.MILLIS));
        long justInserted = insert("PENDING", cutoff); /* 刚插入的行：updated_at == cutoff */
        long oneMinuteOlder = insert("PENDING", Timestamp.from(cutoff.toInstant().minusSeconds(60)));

        java.util.List<Long> ids = queries.findStalePending(cutoff);

        assertTrue(!ids.contains(justInserted), "updated_at == cutoff 的行不得入选（严格 <，阈值 0 也生效）");
        assertTrue(ids.contains(oneMinuteOlder), "cutoff-1 分钟的行应入选（阈值 0 随参数走）");
    }

    /* ===== T4.79/P-02：findTaskStatus（真 H2） ===== */

    /** findTaskStatus：行存在返回 status+updated_at；行不存在返回 null（真 SQL——漏传 id 参数时本测试变红）。 */
    @Test
    void findTaskStatusBindsIdAndReturnsRowOrNull() {
        long id = insert("RUNNING", runStart);

        java.util.Map<String, Object> row = queries.findTaskStatus(id);
        assertEquals("RUNNING", row.get("status"), "真 SQL 必须真绑定 id 参数并返回行");
        assertEquals(runStart, row.get("updated_at"));

        org.junit.jupiter.api.Assertions.assertNull(queries.findTaskStatus(999_999L), "行不存在必须返回 null");
    }
}
