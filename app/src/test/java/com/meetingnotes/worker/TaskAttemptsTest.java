package com.meetingnotes.worker;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * T4.94/C6（P-03 测试有效性缺口）：证明 attempts 读写 SQL 在 H2 真库可执行——
 * 替代 {@code markFailure} 原来的 {@code UPDATE … RETURNING}（PG 专用，H2 跑不了，那段 SQL 从未被执行过）。
 */
class TaskAttemptsTest {

    private static final String URL = "jdbc:h2:mem:taskattempts;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    private JdbcTemplate jdbc;
    private TaskAttempts taskAttempts;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "attempts INT NOT NULL DEFAULT 0, updated_at TIMESTAMP)");
        taskAttempts = new TaskAttempts(jdbc);
    }

    private long insertRow() {
        jdbc.update("INSERT INTO task (attempts, updated_at) VALUES (0, now())");
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    /** bump：attempts 0→1→2 逐次自增，read 读回一致。 */
    @Test
    void bumpIncrementsAttemptsStepByStep() {
        long id = insertRow();

        assertEquals(1, taskAttempts.bump(id), "第一次 bump 影响行数应为 1");
        assertEquals(1, taskAttempts.read(id), "attempts 应为 1");
        assertEquals(1, taskAttempts.bump(id), "第二次 bump 影响行数应为 1");
        assertEquals(2, taskAttempts.read(id), "attempts 应为 2");
    }

    /** read：行不存在返回 null（不抛）。 */
    @Test
    void readMissingRowReturnsNull() {
        assertNull(taskAttempts.read(999_999L), "行不存在时 read 必须返回 null");
    }

    /** bump：行不存在返回影响行数 0 且不抛。 */
    @Test
    void bumpMissingRowReturnsZeroAndDoesNotThrow() {
        assertEquals(0, taskAttempts.bump(999_999L), "行不存在时 bump 影响行数应为 0");
        assertNull(taskAttempts.read(999_999L), "bump 不得凭空造行");
    }
}
