package com.meetingnotes.worker;

import com.meetingnotes.common.ApiException;
import com.meetingnotes.task.QueuePublisher;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.util.ReflectionTestUtils;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * T4.61：运行期「陈旧 PENDING」周期清扫。**jdbc 用真实 H2（MODE=PostgreSQL）执行**——
 * 判据的方向（updated_at < cutoff）只有真库才能验证，mock jdbc 会在 A2 负向对照（< 翻转成 >）时假绿
 * （R3 教训：T4.55 审查在 StartupRecovery 身上抓过同类问题）。redis（QueuePublisher）mock。
 * 四条：①陈旧 PENDING 重投且 updated_at 刷新；②新鲜 PENDING 不动；③enabled=false 不查不投；
 * ④投递 503 不崩（warn 继续，失败行不刷新）。
 */
@ExtendWith(MockitoExtension.class)
class StalePendingSweeperTest {

    private static final String URL = "jdbc:h2:mem:sweepdb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
    private static final String QUEUE_KEY = "meetingnotes:task-queue";

    @Mock
    private QueuePublisher queuePublisher;

    private JdbcTemplate jdbc;
    private Timestamp runStart;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), updated_at TIMESTAMP)");
        runStart = new Timestamp(System.currentTimeMillis() - 1000L);
    }

    private long insert(String status, Timestamp updatedAt) {
        jdbc.update("INSERT INTO task (status, updated_at) VALUES (?, ?)", status, updatedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    private StalePendingSweeper newSweeper(boolean enabled) {
        StalePendingSweeper sweeper = new StalePendingSweeper(jdbc, queuePublisher);
        ReflectionTestUtils.setField(sweeper, "enabled", enabled);
        ReflectionTestUtils.setField(sweeper, "staleMinutes", 2L);
        return sweeper;
    }

    /** ① 陈旧 PENDING：重投 + updated_at 刷新（下轮不再重复入队）。 */
    @Test
    void stalePendingIsRequeuedAndTimestampRefreshed() {
        long staleId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));

        newSweeper(true).sweepStalePending();

        verify(queuePublisher).publish(staleId);
        Integer refreshed = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at > ?", Integer.class, staleId, runStart);
        assertEquals(1, refreshed, "陈旧 PENDING 应被 sweep 刷新 updated_at");
    }

    /** ② 新鲜 PENDING（刚创建、未到阈值）：不重投、不刷新。 */
    @Test
    void freshPendingIsNeverTouched() {
        long freshId = insert("PENDING", runStart);

        newSweeper(true).sweepStalePending();

        verify(queuePublisher, never()).publish(freshId);
        Integer untouched = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at <= ?", Integer.class, freshId, runStart);
        assertEquals(1, untouched, "新鲜 PENDING 不得被 sweep 碰");
    }

    /** ③ enabled=false：完全不动（无重投、无状态变化）。 */
    @Test
    void disabledSweeperTouchesNothing() {
        long staleId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));

        newSweeper(false).sweepStalePending();

        verify(queuePublisher, never()).publish(staleId);
        Integer untouched = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at <= ?", Integer.class, staleId, runStart);
        assertEquals(1, untouched, "disabled 时陈旧行也不得被碰");
    }

    /** ④ 单条投递 503：不崩，失败行不刷新（下一轮再兜底），其余行照常处理。 */
    @Test
    void publishFailureDoesNotCrashAndSkipsRefresh() {
        long failingId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));
        long okId = insert("PENDING", Timestamp.from(runStart.toInstant().minusSeconds(180)));
        doThrow(new ApiException(503, "QUEUE_UNAVAILABLE", "队列暂不可用，请稍后重试"))
                .when(queuePublisher).publish(failingId);

        assertDoesNotThrow(() -> newSweeper(true).sweepStalePending());

        verify(queuePublisher).publish(failingId);
        verify(queuePublisher).publish(okId);
        Integer notRefreshed = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at <= ?", Integer.class, failingId, runStart);
        assertEquals(1, notRefreshed, "投递失败的行不得刷新（下轮再兜底）");
        Integer refreshed = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND updated_at > ?", Integer.class, okId, runStart);
        assertEquals(1, refreshed, "成功的行应被刷新");
    }
}
