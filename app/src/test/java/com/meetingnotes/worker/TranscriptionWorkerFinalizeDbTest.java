package com.meetingnotes.worker;

import com.meetingnotes.ai.StructuringService;
import com.meetingnotes.ai.TranscriptPunctuator;
import com.meetingnotes.asr.AsrClient;
import com.meetingnotes.webhook.WebhookDeliveryService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.Mockito;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.data.redis.core.StringRedisTemplate;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import software.amazon.awssdk.services.s3.S3Client;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.doNothing;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * T4.102/C7-5/C7-6（真 H2，MODE=PostgreSQL）：收口 SQL 必须真执行——
 * 「失败→重试→成功」路径（task 行带 error_code='ASR_ERROR'）走完 finalizeResult 后：
 * status='DONE' 且 **error_code IS NULL**（T4.102 新语义），除 status/error_code/updated_at
 * 外其它列原样（user_id/source_uri/attempts/deleted_at 不被触碰）。
 * saveTranscript 用 spy 打桩（其 ?::jsonb 在 H2 不可执行，且本测试只关心收口 UPDATE）。
 */
@ExtendWith(MockitoExtension.class)
class TranscriptionWorkerFinalizeDbTest {

    private static final String URL = "jdbc:h2:mem:workerfinalize;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    @Mock
    private StringRedisTemplate redis;
    @Mock
    private S3Client s3;
    @Mock
    private AsrClient asrClient;
    @Mock
    private StructuringService structuringService;
    @Mock
    private TranscriptPunctuator punctuator;
    @Mock
    private WebhookDeliveryService webhookService;
    @Mock
    private PasteTextReader pasteTextReader;
    @Mock
    private MonoWavExtractor monoWavExtractor;
    @Mock
    private com.meetingnotes.task.QueuePublisher queuePublisher;
    @Mock
    private com.meetingnotes.task.DeadTaskRecorder deadTaskRecorder;
    @Mock
    private TaskHeartbeat taskHeartbeat;
    @Mock
    private TaskAttempts taskAttempts;

    private JdbcTemplate jdbc;
    private long taskId;

    @BeforeEach
    void createSchemaAndRow() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("DROP TABLE IF EXISTS task_result");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "user_id BIGINT, status VARCHAR(16), source_uri VARCHAR(512), "
                + "attempts INT NOT NULL DEFAULT 0, error_code VARCHAR(64), "
                + "deleted_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE)");
        jdbc.execute("CREATE TABLE task_result (task_id BIGINT PRIMARY KEY, transcript VARCHAR(2048))");
        jdbc.update("INSERT INTO task (user_id, status, source_uri, attempts, error_code, updated_at) "
                + "VALUES (1, 'RETRYING', 's3://meetingnotes/tasks/7/a.wav', 2, 'ASR_ERROR', now())");
        taskId = jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    /** 真库 jdbc + 其余依赖 mock；saveTranscript 打桩（只关心收口 UPDATE）。 */
    private TranscriptionWorker newWorkerWithRealDb() {
        TranscriptionWorker worker = new TranscriptionWorker(redis, jdbc, s3, asrClient,
                structuringService, punctuator, webhookService, pasteTextReader, monoWavExtractor,
                queuePublisher, deadTaskRecorder, taskHeartbeat, "meetingnotes:task-queue", 10, "meetingnotes", 3,
                new RedisUnavailableReporter(60, 2, java.time.Clock.systemUTC()), taskAttempts,
                new com.meetingnotes.worker.TaskTranscriber(asrClient),
                new RetryBackoff(30, 300, 5000));
        return worker;
    }

    /** C7-5：失败→重试→成功路径：DONE 且 error_code IS NULL（T4.102 前该行残留 ASR_ERROR）。 */
    @Test
    void finalizeClearsErrorCodeOnSuccess() {
        TranscriptionWorker worker = Mockito.spy(newWorkerWithRealDb());
        doNothing().when(worker).saveTranscript(anyLong(), anyString(), any());
        when(structuringService.structure(anyLong(), anyString()))
                .thenThrow(new RuntimeException("AI down")); // D-068：AI 失败不阻塞 DONE

        worker.finalizeResult(taskId, "收口文本", null);

        assertEquals("DONE", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, taskId));
        assertNull(jdbc.queryForObject("SELECT error_code FROM task WHERE id = ?", String.class, taskId),
                "T4.102：成功收口必须清 error_code（不得残留 ASR_ERROR）");
        assertNotNull(jdbc.queryForObject("SELECT updated_at FROM task WHERE id = ?", Timestamp.class, taskId));
        verify(webhookService).onTerminal(taskId, "DONE");
    }

    /** C7-6：收口 SQL 只动 status/error_code/updated_at——其它列原样。 */
    @Test
    void finalizeTouchesOnlyStatusErrorCodeUpdatedAt() {
        TranscriptionWorker worker = Mockito.spy(newWorkerWithRealDb());
        doNothing().when(worker).saveTranscript(anyLong(), anyString(), any());
        when(structuringService.structure(anyLong(), anyString()))
                .thenThrow(new RuntimeException("AI down"));

        worker.finalizeResult(taskId, "收口文本", null);

        assertEquals(1L, jdbc.queryForObject("SELECT user_id FROM task WHERE id = ?", Long.class, taskId));
        assertEquals("s3://meetingnotes/tasks/7/a.wav",
                jdbc.queryForObject("SELECT source_uri FROM task WHERE id = ?", String.class, taskId));
        assertEquals(2, jdbc.queryForObject("SELECT attempts FROM task WHERE id = ?", Integer.class, taskId));
        assertNull(jdbc.queryForObject("SELECT deleted_at FROM task WHERE id = ?", Timestamp.class, taskId));
        assertNull(jdbc.queryForObject("SELECT error_code FROM task WHERE id = ?", String.class, taskId));
        assertTrue(jdbc.queryForObject("SELECT updated_at IS NOT NULL FROM task WHERE id = ?", Boolean.class, taskId));
    }
}
