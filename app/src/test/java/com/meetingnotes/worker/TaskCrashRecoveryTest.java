package com.meetingnotes.worker;

import com.meetingnotes.task.DeadTaskRecorder;
import com.meetingnotes.webhook.WebhookDeliveryService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.ArgumentMatchers.contains;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

/**
 * T4.94/C6（P-03）：崩溃回收的 SQL 语义必须真库执行——真 H2 建 task 表 + 真 TaskAttempts，
 * DeadTaskRecorder / WebhookDeliveryService mock（DEAD+dead_letter+退款的 SQL 断言在 DeadTaskRecorderTest）。
 * 覆盖：NEED_REQUEUE（PENDING+attempts+1 原子生效）、达上限 DEAD（markDead/onTerminal 恰好各 1 次）、
 * PENDING 跳过不误计、行不存在不抛、上限比较是 &gt;=（边界 = 上限即 DEAD）。
 */
@ExtendWith(MockitoExtension.class)
class TaskCrashRecoveryTest {

    private static final String URL = "jdbc:h2:mem:crashrecovery;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    @Mock
    private DeadTaskRecorder deadTaskRecorder;
    @Mock
    private WebhookDeliveryService webhookService;

    private JdbcTemplate jdbc;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), attempts INT NOT NULL DEFAULT 0, updated_at TIMESTAMP)");
    }

    private TaskCrashRecovery newRecovery(int maxRetries) {
        return new TaskCrashRecovery(jdbc, new TaskAttempts(jdbc), deadTaskRecorder, webhookService, maxRetries);
    }

    private long insert(String status, int attempts) {
        jdbc.update("INSERT INTO task (status, attempts, updated_at) VALUES (?, ?, now())", status, attempts);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    /** 用例 1：RUNNING + attempts=1（max=3）→ NEED_REQUEUE，行变 PENDING 且 attempts=2（自增真执行）。 */
    @Test
    void runningBelowLimitNeedsRequeueAndBumpsAttempts() {
        long id = insert("RUNNING", 1);

        TaskCrashRecovery.Outcome outcome = newRecovery(3).recover(id, "startup");

        assertEquals(TaskCrashRecovery.Outcome.NEED_REQUEUE, outcome);
        String status = jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id);
        assertEquals("PENDING", status, "回收后行应为 PENDING");
        Integer attempts = jdbc.queryForObject("SELECT attempts FROM task WHERE id = ?", Integer.class, id);
        assertEquals(2, attempts, "attempts 应自增为 2");
        verifyNoInteractions(deadTaskRecorder, webhookService);
    }

    /** 用例 2：RUNNING + attempts=2（max=3）→ 自增到 3 达上限 → DEAD；markDead（WORKER_CRASH，含 sweeper）与 onTerminal 恰好各 1 次。 */
    @Test
    void runningAtLimitMarksDeadExactlyOnce() {
        long id = insert("RUNNING", 2);

        TaskCrashRecovery.Outcome outcome = newRecovery(3).recover(id, "sweeper");

        assertEquals(TaskCrashRecovery.Outcome.DEAD, outcome);
        verify(deadTaskRecorder, times(1)).markDead(eq(id), eq("WORKER_CRASH"), contains("sweeper"));
        verify(webhookService, times(1)).onTerminal(id, "DEAD");
    }

    /** 用例 3：PENDING 行 → SKIPPED 且 attempts 不变、无 markDead（不误计非崩溃行）。 */
    @Test
    void pendingRowIsSkippedAndAttemptsUnchanged() {
        long id = insert("PENDING", 1);

        TaskCrashRecovery.Outcome outcome = newRecovery(3).recover(id, "sweeper");

        assertEquals(TaskCrashRecovery.Outcome.SKIPPED, outcome);
        Integer attempts = jdbc.queryForObject("SELECT attempts FROM task WHERE id = ?", Integer.class, id);
        assertEquals(1, attempts, "SKIPPED 不得动 attempts");
        verifyNoInteractions(deadTaskRecorder);
    }

    /** 用例 4：行不存在 → SKIPPED 不抛。 */
    @Test
    void missingRowIsSkippedWithoutThrowing() {
        assertDoesNotThrow(() -> {
            TaskCrashRecovery.Outcome outcome = newRecovery(3).recover(999_999L, "startup");
            assertEquals(TaskCrashRecovery.Outcome.SKIPPED, outcome);
        });
        verifyNoInteractions(deadTaskRecorder, webhookService);
    }

    /** 用例 5（参数化 max=3 与 max=1）：自增后 attempts 恰等于上限即 DEAD——证明边界比较是 >= 而非 >（> 时本用例必红）。 */
    @ParameterizedTest
    @ValueSource(ints = {3, 1})
    void limitComparisonIsGreaterThanOrEqual(int maxRetries) {
        long id = insert("RUNNING", maxRetries - 1); // 自增后 = maxRetries，恰达边界

        TaskCrashRecovery.Outcome outcome = newRecovery(maxRetries).recover(id, "startup");

        assertEquals(TaskCrashRecovery.Outcome.DEAD, outcome,
                "attempts 自增到 " + maxRetries + "（恰等于上限）必须 DEAD（>= 而非 >）");
        verify(deadTaskRecorder, times(1)).markDead(eq(id), eq("WORKER_CRASH"), contains("startup"));
    }
}
