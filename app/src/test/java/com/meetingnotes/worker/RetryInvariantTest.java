package com.meetingnotes.worker;

import com.meetingnotes.task.DeadTaskRecorder;
import com.meetingnotes.task.QueuePublisher;
import com.meetingnotes.webhook.WebhookDeliveryService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.data.redis.core.StringRedisTemplate;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import software.amazon.awssdk.services.s3.S3Client;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.Mockito.when;

/** T4.100/C7/C9-5：真 H2 跑完 C4 失败写回 + C5 到期抢占后，RETRYING 且 next_retry_at IS NULL 的行数必须为 0。 */
@ExtendWith(MockitoExtension.class)
class RetryInvariantTest {
    private static final String URL = "jdbc:h2:mem:retryinv;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    @Mock private StringRedisTemplate redis;
    @Mock private S3Client s3;
    @Mock private com.meetingnotes.asr.AsrClient asrClient;
    @Mock private com.meetingnotes.ai.StructuringService structuringService;
    @Mock private com.meetingnotes.ai.TranscriptPunctuator punctuator;
    @Mock private com.meetingnotes.webhook.WebhookDeliveryService webhookService;
    @Mock private PasteTextReader pasteTextReader;
    @Mock private MonoWavExtractor monoWavExtractor;
    @Mock private QueuePublisher queuePublisher;
    @Mock private DeadTaskRecorder deadTaskRecorder;
    @Mock private TaskHeartbeat taskHeartbeat;

    private JdbcTemplate jdbc;
    private TaskAttempts taskAttempts;
    private RetryDueSweeper sweeper;
    private TranscriptionWorker worker;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), attempts INT DEFAULT 0, error_code VARCHAR(64), "
                + "next_retry_at TIMESTAMP, updated_at TIMESTAMP, deleted_at TIMESTAMP, "
                + "source_type VARCHAR(16), source_uri VARCHAR(512), request_id VARCHAR(64), language VARCHAR(8))");
        taskAttempts = new TaskAttempts(jdbc);
        sweeper = new RetryDueSweeper(jdbc, queuePublisher);
        worker = new TranscriptionWorker(redis, jdbc, s3, asrClient, structuringService, punctuator, webhookService,
                pasteTextReader, monoWavExtractor, queuePublisher, deadTaskRecorder, taskHeartbeat,
                "meetingnotes:task-queue", 2, "meetingnotes", 3,
                new RedisUnavailableReporter(60, 2, java.time.Clock.systemUTC()), taskAttempts,
                new TaskTranscriber(asrClient), new RetryBackoff(30, 300, 5000));
    }

    private long insertPending() {
        jdbc.update("INSERT INTO task (status, attempts, updated_at) VALUES ('PENDING', 0, now())");
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    private int brokenRetryingRows() {
        return jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE status = 'RETRYING' AND next_retry_at IS NULL", Integer.class);
    }

    @Test
    void markFailureKeepsInvariant() {
        long id = insertPending();

        org.springframework.test.util.ReflectionTestUtils.invokeMethod(worker, "markFailure", id,
                new ProcessingException("ASR_ERROR", "连接拒绝", null));

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        assertEquals(0, brokenRetryingRows(), "C4：失败写回后不得存在 RETRYING + next_retry_at IS NULL");
    }

    @Test
    void sweeperPublishFailureKeepsInvariant() {
        long id = insertPending();
        org.springframework.test.util.ReflectionTestUtils.invokeMethod(worker, "markFailure", id,
                new ProcessingException("ASR_ERROR", "连接拒绝", null));
        // 把到期时间拨到过去 → 下一轮抢占；投递失败回退 RETRYING 必须保留非空 next_retry_at
        jdbc.update("UPDATE task SET next_retry_at = ? WHERE id = ?",
                new Timestamp(System.currentTimeMillis() - 1000L), id);
        when(queuePublisher.tryPublishToTail(id)).thenReturn(false);

        sweeper.sweep();

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        assertEquals(0, brokenRetryingRows(), "C5 投递失败回退后不得存在 RETRYING + next_retry_at IS NULL");
    }

    @Test
    void markDeadClearsNextRetryAt() {
        long id = insertPending();
        org.springframework.test.util.ReflectionTestUtils.invokeMethod(worker, "markFailure", id,
                new ProcessingException("ASR_ERROR", "连接拒绝", null));
        jdbc.update("UPDATE task SET attempts = 3 WHERE id = ?", id); // 下次失败耗尽

        org.springframework.test.util.ReflectionTestUtils.invokeMethod(worker, "markFailure", id,
                new ProcessingException("ASR_ERROR", "连接拒绝", null));

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id),
                "DeadTaskRecorder 是 mock，本用例只验 worker 调 markDead 前不变量仍成立");
        assertEquals(0, brokenRetryingRows());
    }
}
