package com.meetingnotes.worker;

import com.meetingnotes.task.QueuePublisher;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/** T4.100/C5/C9-2：到期重试抢占的 SQL 语义真 H2 覆盖（条件 UPDATE + 原子抢占 + 软删除/未到期不动）。 */
@ExtendWith(MockitoExtension.class)
class RetryDueSweeperTest {
    private static final String URL = "jdbc:h2:mem:retrydue;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    @Mock
    private QueuePublisher queuePublisher;

    private JdbcTemplate jdbc;
    private RetryDueSweeper sweeper;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "status VARCHAR(16), attempts INT DEFAULT 0, next_retry_at TIMESTAMP, "
                + "updated_at TIMESTAMP, deleted_at TIMESTAMP)");
        sweeper = new RetryDueSweeper(jdbc, queuePublisher);
    }

    private long insert(String status, Timestamp due, Timestamp deletedAt) {
        jdbc.update("INSERT INTO task (status, next_retry_at, updated_at, deleted_at) VALUES (?, ?, now(), ?)",
                status, due, deletedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    @Test
    void dueRetryingIsClaimedToPendingAndPublished() {
        long id = insert("RETRYING", new Timestamp(System.currentTimeMillis() - 1000L), null);
        when(queuePublisher.tryPublishToTail(id)).thenReturn(true);

        sweeper.sweep();

        assertEquals("PENDING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        assertEquals(0, jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND next_retry_at IS NOT NULL", Integer.class, id),
                "离开 RETRYING 必须清 next_retry_at");
        verify(queuePublisher).tryPublishToTail(id);
    }

    @Test
    void notYetDueRetryingIsLeftUntouchedAndNotPublished() {
        long id = insert("RETRYING", new Timestamp(System.currentTimeMillis() + 60_000L), null);

        sweeper.sweep();

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        verify(queuePublisher, never()).tryPublishToTail(anyLong());
    }

    @Test
    void softDeletedRetryingIsNotResurrected() {
        long id = insert("RETRYING", new Timestamp(System.currentTimeMillis() - 1000L),
                new Timestamp(System.currentTimeMillis()));

        sweeper.sweep();

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        verify(queuePublisher, never()).tryPublishToTail(anyLong());
    }

    @Test
    void publishFailureRollsBackToRetryingWithDueTimePreserved() {
        long id = insert("RETRYING", new Timestamp(System.currentTimeMillis() - 1000L), null);
        when(queuePublisher.tryPublishToTail(id)).thenReturn(false);

        sweeper.sweep();

        assertEquals("RETRYING", jdbc.queryForObject("SELECT status FROM task WHERE id = ?", String.class, id));
        assertEquals(1, jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND next_retry_at IS NOT NULL", Integer.class, id),
                "投递失败保留 next_retry_at（下一轮再试；不变量 RETRYING ⇒ 非空）");
        verify(queuePublisher).tryPublishToTail(id);
    }

    @Test
    void runtimeExceptionFromQueueDoesNotEscape() {
        long id = insert("RETRYING", new Timestamp(System.currentTimeMillis() - 1000L), null);
        when(queuePublisher.tryPublishToTail(id)).thenThrow(new RuntimeException("Redis down"));

        org.junit.jupiter.api.Assertions.assertDoesNotThrow(sweeper::sweep);
    }
}
