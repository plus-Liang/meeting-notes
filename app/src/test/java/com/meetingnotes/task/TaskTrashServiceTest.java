package com.meetingnotes.task;

import com.meetingnotes.common.ApiException;
import com.meetingnotes.common.UserContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import software.amazon.awssdk.services.s3.S3Client;

import java.sql.Timestamp;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;

/**
 * T4.96/C11（D-245）：回收站服务真 H2（MODE=PostgreSQL）——恢复 / 彻底删 / 清空 / 到期清理的
 * SQL 必须真执行（mock 层证不了 deleted_at 条件与 4 表 FK 顺序）。
 * 关键负向：purge 对 deleted_at IS NULL 的在用任务**必须拒绝**（防误删）；retention-days=0 回退 30 不误删。
 */
class TaskTrashServiceTest {

    private static final String URL = "jdbc:h2:mem:trashsvc;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
    private static final Clock CLOCK = Clock.fixed(Instant.parse("2026-11-26T00:00:00Z"), ZoneOffset.UTC);

    private JdbcTemplate jdbc;
    private S3Client s3;
    private TaskDeleteService deleteService;
    private TransactionTemplate tx;
    private TaskTrashService service;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS webhook_delivery");
        jdbc.execute("DROP TABLE IF EXISTS dead_letter");
        jdbc.execute("DROP TABLE IF EXISTS task_result");
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "user_id BIGINT, status VARCHAR(16), source_uri VARCHAR(512), content_hash VARCHAR(64), "
                + "attempts INT NOT NULL DEFAULT 0, error_code VARCHAR(64), "
                + "deleted_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE)");
        jdbc.execute("CREATE TABLE task_result (task_id BIGINT PRIMARY KEY, transcript VARCHAR(2048), summary VARCHAR(2048))");
        jdbc.execute("CREATE TABLE dead_letter (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "task_id BIGINT, reason VARCHAR(512))");
        jdbc.execute("CREATE TABLE webhook_delivery (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "task_id BIGINT, url VARCHAR(256))");
        s3 = Mockito.mock(S3Client.class);
        PlatformTransactionManager tm = new DataSourceTransactionManager(
                new org.springframework.jdbc.datasource.DriverManagerDataSource(URL));
        tx = new TransactionTemplate(tm);
        deleteService = new TaskDeleteService(jdbc, tx, s3, "meetingnotes");
        UserContext.set(1L);
    }

    @AfterEach
    void clearContext() {
        UserContext.clear();
    }

    private TaskTrashService newService(int retentionDays) {
        return new TaskTrashService(jdbc, tx, deleteService, CLOCK, retentionDays);
    }

    private long insertTask(long userId, String status, boolean trashed, int deletedDaysAgo) {
        Timestamp deletedAt = trashed
                ? Timestamp.from(CLOCK.instant().minusSeconds((long) deletedDaysAgo * 86400))
                : null;
        jdbc.update("INSERT INTO task (user_id, status, source_uri, content_hash, attempts, deleted_at) "
                        + "VALUES (?, ?, ?, ?, 0, ?)",
                userId, status, "s3://meetingnotes/tasks/x/a.wav", "hash-" + System.nanoTime(), deletedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    private void insertChildRows(long taskId) {
        jdbc.update("INSERT INTO task_result (task_id, transcript, summary) VALUES (?, '转写全文', '纪要')", taskId);
        jdbc.update("INSERT INTO dead_letter (task_id, reason) VALUES (?, 'ASR 连接超时')", taskId);
        jdbc.update("INSERT INTO webhook_delivery (task_id, url) VALUES (?, 'http://probe/callback')", taskId);
    }

    private int count(String table, long taskId) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM " + table + " WHERE "
                + ("task".equals(table) ? "id" : "task_id") + " = ?", Integer.class, taskId);
        return n == null ? 0 : n;
    }

    /* ===== restore ===== */

    @Test
    void restoreClearsDeletedAt() {
        long id = insertTask(1L, "DEAD", true, 3);
        insertChildRows(id);

        newService(30).restore(id);

        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM task WHERE id = ? AND deleted_at IS NULL", Integer.class, id);
        assertEquals(1, n, "恢复 = deleted_at 清空");
    }

    @Test
    void restoreKeepsTranscriptAndDeadLetterReason() {
        long id = insertTask(1L, "DONE", true, 5);
        insertChildRows(id);

        newService(30).restore(id);

        assertEquals(1, count("task_result", id), "恢复后转写/纪要仍在");
        assertEquals(1, count("dead_letter", id), "恢复后死信原因仍在（详情页 error_message 数据源）");
    }

    @Test
    void restoreNotInTrashThrows404() {
        long id = insertTask(1L, "DONE", false, 0); // 未删除

        ApiException e = assertThrows(ApiException.class, () -> newService(30).restore(id));
        assertEquals(404, e.getStatus());
        assertEquals("TASK_NOT_FOUND", e.getCode());
    }

    @Test
    void restoreForeignOrMissingThrows404() {
        ApiException missing = assertThrows(ApiException.class, () -> newService(30).restore(999_999L));
        assertEquals(404, missing.getStatus());
        long id = insertTask(2L, "DONE", true, 1); // 别人的回收站任务
        ApiException foreign = assertThrows(ApiException.class, () -> newService(30).restore(id));
        assertEquals(404, foreign.getStatus());
    }

    /** 批量恢复：去重保序、逐条部分成功，@return 只含成功 id（口径同批量删除）。 */
    @Test
    void restoreBatchReturnsOnlyRestoredIdsInOrder() {
        long a = insertTask(1L, "DONE", true, 1);
        long b = insertTask(1L, "DONE", false, 0); // 不在回收站 → 跳过
        long c = insertTask(1L, "DEAD", true, 2);

        List<Long> restored = newService(30).restoreBatch(List.of(a, b, a, c));

        assertEquals(List.of(a, c), restored, "去重保序，且不含不在回收站的行");
    }

    @Test
    void restoreBatchRejectsEmptyOrOver100With400() {
        assertEquals(400, assertThrows(ApiException.class, () -> newService(30).restoreBatch(List.of())).getStatus());
        List<Long> tooMany = new java.util.ArrayList<>();
        for (long i = 1; i <= 101; i++) {
            tooMany.add(i);
        }
        assertEquals(400, assertThrows(ApiException.class, () -> newService(30).restoreBatch(tooMany)).getStatus());
    }

    /* ===== purge ===== */

    @Test
    void purgeDeletesAllFourTablesAndObject() {
        long id = insertTask(1L, "DONE", true, 10);
        insertChildRows(id);

        assertTrue(newService(30).purge(id), "回收站任务彻底删除成功");

        assertEquals(0, count("task", id), "task 行物理删除");
        assertEquals(0, count("task_result", id), "task_result 行物理删除");
        assertEquals(0, count("dead_letter", id), "dead_letter 行物理删除");
        assertEquals(0, count("webhook_delivery", id), "webhook_delivery 行物理删除");
        Mockito.verify(s3).deleteObject(any(software.amazon.awssdk.services.s3.model.DeleteObjectRequest.class));
    }

    /** 关键负向：deleted_at IS NULL 的在用任务**绝不许 purge**（否则误删正在用的任务）。 */
    @Test
    void purgeRefusesActiveTaskNotInTrash() {
        long id = insertTask(1L, "DONE", false, 0);
        insertChildRows(id);

        assertFalse(newService(30).purge(id), "不在回收站的任务必须拒绝");
        assertEquals(1, count("task", id), "在用任务行完好");
        assertEquals(1, count("task_result", id));
    }

    @Test
    void purgeForeignTaskIsRejected() {
        long id = insertTask(2L, "DONE", true, 1); // 别人的回收站任务
        assertFalse(newService(30).purge(id), "非本人 → false（controller 404）");
        assertEquals(1, count("task", id));
    }

    /** 并发/重复 purge：第二次 0 行 → false（幂等，不 500）。 */
    @Test
    void doublePurgeOnlyFirstWins() {
        long id = insertTask(1L, "DEAD", true, 20);
        assertTrue(newService(30).purge(id));
        assertFalse(newService(30).purge(id), "第二次已无行 → false");
        assertEquals(0, count("task", id));
    }

    @Test
    void purgeAllOnlyTouchesOwnTrashRows() {
        long mine1 = insertTask(1L, "DONE", true, 1);
        long mine2 = insertTask(1L, "DEAD", true, 2);
        long active = insertTask(1L, "DONE", false, 0);
        long others = insertTask(2L, "DONE", true, 1);

        int purged = newService(30).purgeAll();

        assertEquals(2, purged, "只清当前用户回收站");
        assertEquals(0, count("task", mine1));
        assertEquals(0, count("task", mine2));
        assertEquals(1, count("task", active), "在用任务不动");
        assertEquals(1, count("task", others), "他人回收站任务不动");
    }

    /* ===== purgeExpired（Java 侧 cutoff） ===== */

    @Test
    void purgeExpiredDeletesExpiredRows() {
        long id = insertTask(1L, "DONE", true, 31); // 31 天前 > retention 30

        assertEquals(1, newService(30).purgeExpired(200));
        assertEquals(0, count("task", id));
    }

    @Test
    void purgeExpiredKeepsRowsWithinRetention() {
        long id = insertTask(1L, "DONE", true, 10); // 10 天前 < 30

        assertEquals(0, newService(30).purgeExpired(200));
        assertEquals(1, count("task", id), "保留期内不删");
    }

    @Test
    void purgeExpiredRespectsLimit() {
        long a = insertTask(1L, "DONE", true, 31);
        long b = insertTask(1L, "DONE", true, 32);
        long c = insertTask(1L, "DONE", true, 33);

        assertEquals(2, newService(30).purgeExpired(2), "limit=2 只清 2 条（deleted_at ASC）");
        assertEquals(1, count("task", a) + count("task", b) + count("task", c), "剩 1 条下一轮继续");
    }

    /** 关键负向：retention-days=0 属误配 → 回退 30（cutoff=now-30），**不得**把整个回收站清空。 */
    @Test
    void retentionDaysZeroFallsBackTo30AndDoesNotWipeTrash() {
        long recent = insertTask(1L, "DONE", true, 10); // 10 天前：回退 30 后未到期

        assertEquals(0, newService(0).purgeExpired(200), "0 配置回退 30，10 天前的行绝不误删");
        assertEquals(1, count("task", recent));
    }
}
