package com.meetingnotes.task;

import com.meetingnotes.common.UserContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import software.amazon.awssdk.services.s3.S3Client;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;

/**
 * T4.102/C7-3/C7-4（真 H2，MODE=PostgreSQL）：删除语义必须真执行——
 * ①正常删除成功一次，再删同一 id → NOT_FOUND（404），deleted_at 不变；
 * ②已在回收站（deleted_at 非空）的任务再删 → NOT_FOUND，且 deleted_at **不被刷新**
 * （30 天计时不会被二次删除重置）。mock 层证不了 WHERE 条件的方向（K-229），必须真库。
 */
class TaskDeleteServiceDbTest {

    private static final String URL = "jdbc:h2:mem:delsvc;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    private JdbcTemplate jdbc;
    private TaskDeleteService service;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS task");
        jdbc.execute("CREATE TABLE task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "user_id BIGINT, status VARCHAR(16), source_uri VARCHAR(512), "
                + "error_code VARCHAR(64), deleted_at TIMESTAMP WITH TIME ZONE, updated_at TIMESTAMP WITH TIME ZONE)");
        PlatformTransactionManager tm = new DataSourceTransactionManager(
                new DriverManagerDataSource(URL));
        TransactionTemplate tx = new TransactionTemplate(tm);
        service = new TaskDeleteService(jdbc, tx, Mockito.mock(S3Client.class), "meetingnotes");
        UserContext.set(1L);
    }

    @AfterEach
    void clearContext() {
        UserContext.clear();
    }

    private long insertTask(String status, java.sql.Timestamp deletedAt) {
        jdbc.update("INSERT INTO task (user_id, status, source_uri, error_code, deleted_at, updated_at) "
                + "VALUES (?, ?, ?, NULL, ?, now())", 1L, status, "s3://meetingnotes/tasks/x/a.wav", deletedAt);
        return jdbc.queryForObject("SELECT MAX(id) FROM task", Long.class);
    }

    private String deletedAtOf(long id) {
        return jdbc.queryForObject("SELECT CAST(deleted_at AS VARCHAR) FROM task WHERE id = ?", String.class, id);
    }

    /** C7-4：正常删除成功一次；随后再删 → NOT_FOUND（404），deleted_at 保持第一次的值。 */
    @Test
    void normalDeleteSucceedsOnceThenNotFound() {
        long id = insertTask("DONE", null);

        TaskDeleteService.DeleteOutcome first = service.deleteOne(id);
        org.junit.jupiter.api.Assertions.assertTrue(first.deleted(), "首次删除成功");
        String firstStamp = deletedAtOf(id);

        TaskDeleteService.DeleteOutcome second = service.deleteOne(id);
        org.junit.jupiter.api.Assertions.assertFalse(second.deleted(), "再删不得成功");
        assertEquals("NOT_FOUND", second.reason(), "再删 → NOT_FOUND（控制器映射 404，T4.102）");
        assertEquals(firstStamp, deletedAtOf(id), "deleted_at 不被二次删除刷新（30 天计时不变）");
    }

    /** C7-3：已在回收站（deleted_at 非空）的任务再删 → NOT_FOUND，deleted_at 逐字不变。 */
    @Test
    void trashedTaskRedeleteReturnsNotFoundAndKeepsDeletedAt() {
        long id = insertTask("DONE", java.sql.Timestamp.from(
                java.time.Instant.parse("2026-11-01T00:00:00Z")));
        String before = deletedAtOf(id);

        TaskDeleteService.DeleteOutcome outcome = service.deleteOne(id);
        org.junit.jupiter.api.Assertions.assertFalse(outcome.deleted(), "回收站任务再删不得成功");
        assertEquals("NOT_FOUND", outcome.reason(), "T4.102：回收站再删 → NOT_FOUND（404）");
        assertEquals(before, deletedAtOf(id), "deleted_at 字符串不变（不被刷新）");
        Integer n = jdbc.queryForObject(
                "SELECT COUNT(*) FROM task WHERE id = ? AND deleted_at = TIMESTAMP WITH TIME ZONE '2026-11-01 00:00:00+00:00'",
                Integer.class, id);
        assertEquals(1, n, "deleted_at 行值未被 UPDATE 触碰（仍是回收站原时刻）");
    }
}
