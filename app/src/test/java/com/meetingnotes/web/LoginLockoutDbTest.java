package com.meetingnotes.web;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * T4.81/P-29 后半：LoginLockoutService 的**真实 SQL 语义**（真 H2 MODE=PostgreSQL，mock jdbc 会假绿）：
 * ①连错 5 次（默认上限）→ locked_until 非空且计数=5、第 5 次 recordFailure 返回 true；
 * ②配置 3 → 第 3 次就锁；③解锁（reset）后再错 1 次 → 从 1 重计、不锁；
 * ④locked_until 写过去时间 → 不算锁定（isLocked=false）。
 * 两步式 UPDATE+SELECT（禁 RETURNING，D-085）与 CASE 锁定时点写法在这里被真执行。
 */
class LoginLockoutDbTest {

    private static final String URL = "jdbc:h2:mem:lockoutdb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

    /** 可手推的测试时钟（卡面 Clock 注入口径，禁 sleep）。 */
    private static final class MutableClock extends Clock {
        private Instant instant = Instant.parse("2026-11-24T04:00:00Z");

        void advanceMinutes(long m) { instant = instant.plusSeconds(m * 60); }

        @Override
        public Instant instant() { return instant; }

        @Override
        public ZoneId getZone() { return ZoneOffset.UTC; }

        @Override
        public Clock withZone(ZoneId zone) { return this; }
    }

    private final MutableClock clock = new MutableClock();
    private JdbcTemplate jdbc;

    @BeforeEach
    void createSchema() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(URL));
        jdbc.execute("DROP TABLE IF EXISTS app_user");
        // V8 + V11 的最小列集（H2）：本卡只关心 id / failed_login_attempts / locked_until
        jdbc.execute("CREATE TABLE app_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "username VARCHAR(32), password_hash VARCHAR(200), role VARCHAR(16), "
                + "failed_login_attempts INTEGER NOT NULL DEFAULT 0, locked_until TIMESTAMP)");
    }

    private LoginLockoutService newService(int maxFailures, int lockoutMinutes) {
        return new LoginLockoutService(jdbc, maxFailures, lockoutMinutes, clock);
    }

    private long insertUser() {
        jdbc.update("INSERT INTO app_user (username, password_hash, role) VALUES ('u', 'h', 'USER')");
        return jdbc.queryForObject("SELECT MAX(id) FROM app_user", Long.class);
    }

    private Timestamp lockedUntilOf(long id) {
        return jdbc.queryForObject("SELECT locked_until FROM app_user WHERE id = ?", Timestamp.class, id);
    }

    private int attemptsOf(long id) {
        return jdbc.queryForObject("SELECT failed_login_attempts FROM app_user WHERE id = ?", Integer.class, id);
    }

    /** ① 连错 5 次（默认上限）→ 第 5 次返回 true，locked_until 非空且 ≈ now+15min，计数=5。 */
    @Test
    void fifthConsecutiveFailureLocksAccountWithTimestamp() {
        long id = insertUser();
        LoginLockoutService service = newService(5, 15);

        assertFalse(service.recordFailure(id), "第 1 次失败不应上锁");
        assertFalse(service.recordFailure(id));
        assertFalse(service.recordFailure(id));
        assertFalse(service.recordFailure(id), "第 4 次仍不应上锁");
        assertTrue(service.recordFailure(id), "第 5 次（达到上限）必须上锁");

        assertEquals(5, attemptsOf(id), "计数应累加到 5");
        Timestamp lockedUntil = lockedUntilOf(id);
        assertNotNull(lockedUntil, "上锁必须写入 locked_until");
        long expectedSec = clock.instant().plusSeconds(15 * 60).getEpochSecond();
        assertTrue(Math.abs(lockedUntil.getTime() / 1000 - expectedSec) <= 2,
                "locked_until 应 ≈ now+15min（JVM 时钟传参）：实际 " + lockedUntil);
        assertTrue(service.isLocked(lockedUntil), "刚写的锁定时点必须判定为锁定中");
        assertEquals(15, service.remainingMinutes(lockedUntil), "剩余分钟应向上取整为 15");
    }

    /** ② 配置 3 → 第 3 次就锁（max-failures 生效）。 */
    @Test
    void configuredMaxThreeLocksOnThirdFailure() {
        long id = insertUser();
        LoginLockoutService service = newService(3, 15);

        assertFalse(service.recordFailure(id));
        assertFalse(service.recordFailure(id), "第 2 次不应上锁");
        assertTrue(service.recordFailure(id), "第 3 次（达到配置上限 3）必须上锁");
        assertEquals(3, attemptsOf(id));
        assertNotNull(lockedUntilOf(id));
    }

    /** ③ 解锁（reset 清零）后再错 1 次 → 从 1 重计、不上锁。 */
    @Test
    void afterResetCounterStartsFromOneAgain() {
        long id = insertUser();
        LoginLockoutService service = newService(3, 15);
        service.recordFailure(id);
        service.recordFailure(id);
        service.recordFailure(id); // 锁定
        assertEquals(1, service.reset(id), "解锁应影响 1 行");

        assertFalse(service.recordFailure(id), "解锁后第 1 次失败必须从 1 重计且不上锁");
        assertEquals(1, attemptsOf(id), "计数应重置为 1");
        assertNull(lockedUntilOf(id), "解锁清空后第一次失败不应写 locked_until");
        assertTrue(service.isLocked(null) == false, "locked_until=null 恒不锁定");
    }

    /** ④ locked_until 写过去时间 → 不算锁定（isLocked=false）；新失败不覆盖（CASE ELSE 保留旧值）。 */
    @Test
    void pastLockedUntilIsNotLocked() {
        long id = insertUser();
        Timestamp past = Timestamp.from(clock.instant().minusSeconds(600));
        jdbc.update("UPDATE app_user SET locked_until = ? WHERE id = ?", past, id);

        LoginLockoutService service = newService(5, 15);
        assertFalse(service.isLocked(past), "过去的 locked_until 不算锁定");
        assertFalse(service.recordFailure(id), "未锁定期间失败不上锁");
        assertEquals(past, lockedUntilOf(id), "未达上限时 locked_until 保留旧值（CASE ELSE）");

        // 过去时间也不影响 423 判定路径：isLocked=false → AuthService 走正常验密
        clock.advanceMinutes(1);
        assertFalse(service.isLocked(lockedUntilOf(id)), "推进时钟后仍是过去时间，不锁定");
    }
}
